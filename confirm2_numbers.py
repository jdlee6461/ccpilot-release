"""confirm2 numbers.tex macros (plan §11.4: numbers enter the manuscript only through macros) from confirm2_analysis.py.

    python confirm2_numbers.py --analysis <dir> --out <dir>/confirm2_numbers.tex --prefix cTwoTrial

Every macro carries a comment with its source file, row filter and column. Names use letters only:
  <prefix><Scope><Quantity>...<Target><Stat>, e.g. \\cTwoTrialCombReacqDiffMvplogStaticTNinetyFivePt
Quantities: estimands (a) ReacqDiff, (b) IsoqDiff, (c) WorstDiff (sign: comparator minus method, positive =
improvement; Pt/Lo/Hi 99% conservative bounds, Cls class); worst-group deficit WorstDef and re-acquired deficit
ReacqDef per method (Pt/Lo/Hi 95%); cost ratios RatioHone / RatioHtwo / RatioHfour (Pt/Lo/Hi 95%); RatioHthree only Pt
(fixed-threshold intervals stay in the appendix table) plus ...TNinetyFiveSensLo/SensHi from the H3 sensitivity analysis
(target 0.95, combined blocks, taxi clusters, B = 100, H3 refitted per replicate; plan §6.3, §10.5 rev 72); mean cost Cost;
overall recall Recall; §10.8 statuses ClaimSone... (text).
"""
import argparse
from pathlib import Path

import pandas as pd

TW = {0.90: "Ninety", 0.93: "NinetyThree", 0.95: "NinetyFive", 0.97: "NinetySeven", 0.98: "NinetyEight"}
MN = {"mvp_log": "Mvplog", "qr_ogd": "Qrogd", "static": "Static", "aci_g0005": "Aci", "mondrian_hour_hop_speed": "Mondrian",
      "qr_groups": "Qrgroups", "qr_groups_refit": "Qrrefit", "qr_groups_refit7": "Qrrefitseven",
      "citytrac_nominal": "Citytrac", "spatula_rule|fixed": "Spatula"}
EST = {"reacq_deficit_diff": "ReacqDiff", "isoq4_deficit_diff": "IsoqDiff", "worst_deficit_diff": "WorstDiff"}
STMT = {"S1 core": "SoneCore", "S1 mechanism clause": "SoneMech", "S1 addition (offline group calibration)": "SoneAdd",
        "S2": "Stwo", "S3": "Sthree", "S4": "Sfour"}


def tw(t):
    return TW[round(float(t), 2)]


DIG = dict(zip("0123456789", ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine"]))


def sc_name(s):
    return "Comb" if s == "combined" else "".join(DIG.get(ch, ch) for ch in s).title().replace("_", "")


def f4(x):
    return f"{x:.4f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--analysis", required=True); ap.add_argument("--out", required=True); ap.add_argument("--prefix", default="cTwo")
    ap.add_argument("--h3-sensitivity", help="h3_sensitivity.csv of confirm2_h3_sensitivity.py")
    a = ap.parse_args()
    an = Path(a.analysis); px = a.prefix
    lines = [f"% AUTO-GENERATED by confirm2_numbers.py from {an} -- DO NOT EDIT"]

    def add(name, val, src):
        assert name.isalpha(), name
        lines.append(f"\\newcommand{{\\{name}}}{{{val}}} % {src}")
    E = pd.read_csv(an / "main_estimands.csv").rename(columns={"class": "cls"})
    for r in E.itertuples():
        base = f"{px}{sc_name(r.scope)}{EST[r.estimand]}{MN[r.proposed]}{MN[r.comparator]}T{tw(r.target)}"
        src = f"main_estimands.csv scope={r.scope} estimand={r.estimand} proposed={r.proposed} comparator={r.comparator} target={r.target:g}"
        add(base + "Pt", f4(r.point), src + " col=point")
        add(base + "Lo", f4(r.lo), src + " col=lo (99%, conservative)")
        add(base + "Hi", f4(r.hi), src + " col=hi (99%, conservative)")
        add(base + "Cls", r.cls, src + " col=class")
    D = pd.read_csv(an / "deficits.csv")
    for cell, q in [("WORST", "WorstDef"), ("hopkind=2", "ReacqDef"), ("nn_bin=3", "IsoqDef"), ("grp_all=0", "AllDef")]:
        for r in D[D.cell == cell].itertuples():
            if r.method not in MN:
                continue
            base = f"{px}{sc_name(r.scope)}{q}{MN[r.method]}T{tw(r.target)}"
            src = f"deficits.csv scope={r.scope} cell={cell} method={r.method} target={r.target:g}"
            add(base + "Pt", f4(r.deficit), src + " col=deficit")
            add(base + "Lo", f4(r.lo), src + " col=lo (95%, conservative)")
            add(base + "Hi", f4(r.hi), src + " col=hi (95%, conservative)")
    R = pd.read_csv(an / "cost_ratios.csv")
    for r in R[R.reference.isin(["H1", "H2", "H3", "H4"])].itertuples():
        if r.method not in MN:
            continue
        hn = {"H1": "Hone", "H2": "Htwo", "H3": "Hthree", "H4": "Hfour"}[r.reference]
        base = f"{px}{sc_name(r.scope)}Ratio{hn}{MN[r.method]}T{tw(r.target)}"
        src = f"cost_ratios.csv scope={r.scope} reference={r.reference} method={r.method} target={r.target:g}"
        add(base + "Pt", f"{r.ratio:.3f}", src + " col=ratio")
        if r.reference == "H3":
            continue    # plan §10.5 (rev 72): H3 fixed-threshold intervals only in the appendix table, not as text macros
        add(base + "Lo", f"{r.lo:.3f}", src + " col=lo (95%, conservative)")
        add(base + "Hi", f"{r.hi:.3f}", src + " col=hi (95%, conservative)")
    if a.h3_sensitivity:      # H3 interval for the text: target 0.95, combined blocks, taxi clusters, B = 100, H3 refitted
        for r in pd.read_csv(a.h3_sensitivity).itertuples():
            if r.method not in MN:
                continue
            base = f"{px}CombRatioHthree{MN[r.method]}T{tw(r.target)}Sens"
            src = (f"{a.h3_sensitivity} method={r.method} target={r.target:g} blocks={r.blocks} cluster={r.cluster} B={r.B}"
                   " (H3 refitted per replicate)")
            add(base + "Lo", f"{r.lo_refit:.3f}", src + " col=lo_refit (95%)")
            add(base + "Hi", f"{r.hi_refit:.3f}", src + " col=hi_refit (95%)")
    C = pd.read_csv(an / "costs.csv")
    for r in C.itertuples():
        if r.method not in MN:
            continue
        base = f"{px}{sc_name(r.scope)}{{}}{MN[r.method]}T{tw(r.target)}"
        src = f"costs.csv scope={r.scope} method={r.method} target={r.target:g}"
        add(base.format("Cost"), f"{r.cost_mean:.1f}", src + " col=cost_mean (camera-s per hop, seed mean)")
        add(base.format("Recall"), f4(r.recall_all), src + " col=recall_all (seed mean)")
    if (an / "claims_10_8.csv").exists():
        for r in pd.read_csv(an / "claims_10_8.csv").itertuples():
            txt = str(r.status)
            for ch, rep in [("\\", " "), ("%", "\\%"), ("&", "\\&"), ("_", "\\_"), ("#", "\\#"), ("$", "\\$")]:
                txt = txt.replace(ch, rep)
            add(f"{px}Claim{STMT[r.statement]}{MN[r.method]}", txt,
                f"claims_10_8.csv method={r.method} statement={r.statement} col=status")
    names = [ln.split("}")[0] for ln in lines[1:]]
    assert len(names) == len(set(names)), "duplicate macro names"
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(lines) - 1} macros -> {a.out}")


if __name__ == "__main__":
    main()
