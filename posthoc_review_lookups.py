"""POST HOC (external review, Sean instruction 01 v02 §6): look-ups and macros from stored results (no new method run).

    python posthoc_review_lookups.py

A-2b  exit share on the confirm2 evaluation periods: work/porto_cctv_confirm2/transitions.parquet, transitions with
      t_exit in the block's eval range [start, end) (local dates, Europe/Lisbon; configs/confirm2_analysis.yaml blocks),
      all transitions (exits included, every hop kind); numerator is_exit. Count only.
A-4b  results/porto_cctv_confirm2/analysis/group_cost_ratio_to_static.csv split by group (same rows as
      \\ctwoMechRatioMin/Max: scope combined, methods mvp_log and qr_ogd, five targets, seed means).
A-5   results/porto_cctv_confirm2_posthoc/custody/custody_diffs.csv: paired 5-hop custody differences
      (method - static) for mvp_log and qr_groups_refit, target 0.95, scope combined, chains all / re-acquired-start;
      the stored rows (taxi and day cluster bootstraps, B = 2,000, 95%, conservative bounds); where the stored pair is
      (static, method) the difference and bounds are negated. Output review/../custody/paired/.
A-7b  hindsight (post-hoc) oracle mean cost of the 5 predictors from the stored summary.csv, 2 blocks x 5 targets,
      evaluation seed 0.
Macros: review/review_numbers.tex (prefix \\ctwo...; source comment with file, filter, column, commit).
"""
import subprocess
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

import posthoc_review_common as C
from ccpilot.geo import date_to_unix

A = yaml.safe_load(open("configs/confirm2_analysis.yaml"))
TZ = "Europe/Lisbon"
CUST = Path("results/porto_cctv_confirm2_posthoc/custody")


def commit(path):
    return subprocess.run(["git", "log", "-1", "--format=%h", "--", str(path)], capture_output=True, text=True).stdout.strip()


def fmt(x, nd):
    s = f"{x:.{nd}f}"
    return s.replace("-", "$-$") if s.startswith("-") else s      # a negative value that rounds to zero keeps its sign


def main():
    mac = ["% AUTO-GENERATED by posthoc_review_lookups.py (POST HOC, added during revision (internal review); Sean instruction 01 v02 §6). "
           "Do not edit by hand."]

    def add(name, val, src):
        mac.append(f"% {src}")
        mac.append(f"\\newcommand{{\\{name}}}{{{val}\\xspace}}")

    # ---- A-2b exit share
    tr_p = Path("work/porto_cctv_confirm2/transitions.parquet")
    tr = pd.read_parquet(tr_p, columns=["t_exit", "is_exit"])
    rows = []
    for b, rng in A["blocks"].items():
        lo, hi = date_to_unix(rng["eval"][0], TZ), date_to_unix(rng["eval"][1], TZ)
        m = (tr.t_exit >= lo) & (tr.t_exit < hi)
        rows.append({"scope": b, "eval_start": rng["eval"][0], "eval_end_excl": rng["eval"][1],
                     "n_transitions": int(m.sum()), "n_exit": int(tr.is_exit[m].sum())})
    E = pd.DataFrame(rows)
    E = pd.concat([E, pd.DataFrame([{"scope": "combined", "eval_start": "", "eval_end_excl": "",
                                     "n_transitions": int(E.n_transitions.sum()), "n_exit": int(E.n_exit.sum())}])])
    E["exit_share"] = E.n_exit / E.n_transitions
    E.to_csv(C.OUT / "exit_share_confirm2.csv", index=False)
    src0 = (f"{tr_p} (sha256 of the work file not tracked; preprocessing of ccpilot @ {commit('confirm2_execute.py')}): "
            "transitions with t_exit in the block eval range [start, end) Europe/Lisbon (configs/confirm2_analysis.yaml "
            "blocks), exits included, all hop kinds; n_exit / n_transitions")
    for sc, nm in (("combined", "ctwoExitSharePct"), ("block1", "ctwoExitShareBlockOnePct"),
                   ("block2", "ctwoExitShareBlockTwoPct")):          # names as David's placeholders (verdict 02)
        r = E[E.scope == sc].iloc[0]
        add(nm, fmt(100 * r.exit_share, 1), f"{src0}; scope {sc}: {r.n_exit}/{r.n_transitions}, percent | raw {r.exit_share!r}")
    print(E.to_string(index=False))

    # ---- A-4b group cost ratios
    gp = Path("results/porto_cctv_confirm2/analysis/group_cost_ratio_to_static.csv")
    G = pd.read_csv(gp).query("scope == 'combined' and method in ['mvp_log', 'qr_ogd']")
    for g, nm in (("reacquired", "Reacq"), ("isolation_q4", "Iso")):
        X = G[G.group == g]
        assert len(X) == 10
        for f_, k in (("min", "Min"), ("max", "Max")):
            v = getattr(X.cost_ratio_to_static, f_)()
            row = X.loc[getattr(X.cost_ratio_to_static, f"idx{f_}")()]
            add(f"ctwoMechRatio{nm}{k}", fmt(v, 2),
                f"{gp} @ {commit(gp)}: scope=combined, method in mvp_log, qr_ogd, group={g}, five targets (10 rows); "
                f"{f_} of cost_ratio_to_static (at {row.method}, t={row.target}) | raw {v!r}")
        print(g, X.cost_ratio_to_static.min(), X.cost_ratio_to_static.max())

    # ---- A-5 paired custody differences
    dp = CUST / "custody_diffs.csv"
    D = pd.read_csv(dp, comment="#")
    out = []
    for m in ("mvp_log", "qr_groups_refit"):
        for st, nm in (("all", "All"), ("reacquired", "Reacq")):
            sel = (D.target == 0.95) & (D.scope == "combined") & (D.h == 5) & (D.start == st)
            r1 = D[sel & (D.method_a == m) & (D.method_b == "static")]
            r2 = D[sel & (D.method_a == "static") & (D.method_b == m)]
            assert len(r1) + len(r2) == 1
            if len(r1):
                r = r1.iloc[0]; d, lo, hi = r["diff"], r["lo"], r["hi"]; ltx, htx, ld, hd = r.lo_taxi, r.hi_taxi, r.lo_day, r.hi_day
            else:
                r = r2.iloc[0]; d, lo, hi = -r["diff"], -r["hi"], -r["lo"]; ltx, htx, ld, hd = -r.hi_taxi, -r.lo_taxi, -r.hi_day, -r.lo_day
            out.append({"method": m, "minus": "static", "target": 0.95, "scope": "combined", "chains": st, "h": 5,
                        "diff": d, "lo_taxi": ltx, "hi_taxi": htx, "lo_day": ld, "hi_day": hd, "lo": lo, "hi": hi,
                        "stored_pair": f"{r.method_a}-{r.method_b}", "B": 2000, "level": 0.95})
            tag = {"mvp_log": "MvpLog", "qr_groups_refit": "Qrrefit"}[m]
            src = (f"{dp} @ {commit(dp)}: target 0.95, scope combined, h 5, start {st}, stored pair "
                   f"{r.method_a}-{r.method_b}{' (negated)' if len(r2) else ''}; custody difference {m} - static, "
                   f"percentage points; Lo/Hi = conservative 95% bounds (taxi and day, B = 2000)")
            add(f"ctwoCustodyPaired{nm}{tag}", fmt(100 * d, 2), src + f" | raw {d!r}")
            add(f"ctwoCustodyPaired{nm}{tag}Lo", fmt(100 * lo, 2), src + f" | raw {lo!r}")
            add(f"ctwoCustodyPaired{nm}{tag}Hi", fmt(100 * hi, 2), src + f" | raw {hi!r}")
    P = pd.DataFrame(out)
    (CUST / "paired").mkdir(parents=True, exist_ok=True)
    with open(CUST / "paired" / "custody_paired_5hop.csv", "w") as f:
        f.write("# POST HOC: rows of custody_diffs.csv (no new bootstrap); method - static, k = 5\n")
        P.to_csv(f, index=False)
    print(P[["method", "chains", "diff", "lo", "hi", "stored_pair"]].to_string(index=False))

    # ---- A-7b oracle cost per predictor (stored summary.csv, seed 0)
    rows = []
    for b in C.BLOCKS:
        for t in C.TARGETS:
            S = pd.read_csv(C.run_dir(b, t, 0) / "summary.csv")
            S = S[S.method == "oracle(post-hoc)"].set_index("predictor")
            r = {"block": b, "target": t, "seed": 0}
            for p in C.PREDICTORS:
                r[p] = float(S.loc[p, "cost_mean_cam_s"])
            order = sorted(C.PREDICTORS, key=lambda p: r[p])
            r["order_low_to_high"] = " < ".join(order)
            r["primary_lowest"] = order[0] == C.PRIMARY
            rows.append(r)
    O = pd.DataFrame(rows)
    O.to_csv(C.OUT / "oracle_cost_by_predictor.csv", index=False)
    print(O.to_string(index=False))

    (C.OUT / "review_numbers.tex").write_text("\n".join(mac) + "\n")
    print(f"{(len(mac) - 1) // 2} macros")


if __name__ == "__main__":
    main()
