"""Generate the ten confirm2 run configurations (plan §3, §11.1): 5 targets x 2 blocks.

    python configs/confirm2/generate.py

Each file is configs/porto_cctv_confirm2.yaml with only eval.splits (the block) and eval.target_recall changed, and
out_dir set to results/porto_cctv_confirm2/<block>/t<target>. Evaluation seeds (0-4) and the added comparators and
outputs come from configs/confirm2_analysis.yaml through confirm2_run.py. Writes the diff of every file against the
frozen configs/porto_cctv_confirm.yaml to results/porto_cctv_confirm2/config_diff.txt.
"""
import difflib
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
BASE = ROOT / "configs/porto_cctv_confirm2.yaml"
FROZEN = ROOT / "configs/porto_cctv_confirm.yaml"
A = yaml.safe_load(open(ROOT / "configs/confirm2_analysis.yaml"))
OLD_SPLITS = '''    train: ["2013-07-01", "2013-07-29"]
    cal:   ["2013-07-29", "2013-08-05"]
    test:
      - {name: block1_eval, range: ["2013-08-05", "2013-09-02"]}'''


def main():
    base = BASE.read_text()
    assert base.count(OLD_SPLITS) == 1 and base.count("  target_recall: 0.95\n") == 1
    out_files = []
    for bname, B in A["blocks"].items():
        for t in A["targets"]:
            tag = f"t{int(round(t * 1000)):04d}"
            s = base.replace(OLD_SPLITS, f'''    train: ["{B['train'][0]}", "{B['train'][1]}"]
    cal:   ["{B['cal'][0]}", "{B['cal'][1]}"]
    test:
      - {{name: {bname}_eval, range: ["{B['eval'][0]}", "{B['eval'][1]}"]}}''')
            s = s.replace("  target_recall: 0.95\n", f"  target_recall: {t}\n")
            s = s.replace("out_dir: results/porto_cctv_confirm2\n", f"out_dir: results/porto_cctv_confirm2/{bname}/{tag}\n")
            s = s.replace("# CONFIRMATION 2 BASE CONFIGURATION", f"# CONFIRMATION 2 RUN CONFIGURATION ({bname}, target {t}; generated by configs/confirm2/generate.py from the base)")
            f = ROOT / "configs/confirm2" / f"porto_cctv_confirm2_{bname}_{tag}.yaml"
            f.write_text(s); out_files.append(f)
            cfg = yaml.safe_load(s)
            assert cfg["eval"]["target_recall"] == t and cfg["eval"]["splits"]["train"] == B["train"]
    rep = ROOT / "results/porto_cctv_confirm2/config_diff.txt"
    rep.parent.mkdir(parents=True, exist_ok=True)
    frozen = FROZEN.read_text().splitlines(keepends=True)
    with open(rep, "w") as fh:
        for f in [BASE] + out_files:
            fh.write(f"===== diff configs/porto_cctv_confirm.yaml -> {f.relative_to(ROOT)}\n")
            fh.writelines(difflib.unified_diff(frozen, f.read_text().splitlines(keepends=True), n=0))
            fh.write("\n")
    print(f"{len(out_files)} files; diff -> {rep}")


if __name__ == "__main__":
    sys.exit(main())
