"""POST-HOC (review M3, 2026-10-01): sensitivity to the observation radius and the horizon T_max.
(not pre-registered; additional analysis after the main results)

    python posthoc_geometry.py --make-configs      # writes configs/porto_cctv_confirm_geom_*.yaml
    python posthoc_geometry.py --run               # runs run_pilot.py --stage all for each setting (timed)
    python posthoc_geometry.py --summarize         # 25-group statistics -> results/.../geometry/geometry_summary.csv
    python posthoc_geometry.py --seeds 1 2 3 4 [--settings r30 ...]   # evaluation seeds 1-4 per setting (events reused)
    python posthoc_geometry.py --summarize-seeds   # seeds 0-4 per setting -> geometry_seeds.csv, geometry_seed_pass.csv

Settings (held-out period only; everything else as configs/porto_cctv_confirm.yaml, which is only read):
  r30: observation radius 30 m and merge radius 30 m;  r75: both 75 m;  tmax300: T_max 300 s;  tmax900: T_max 900 s.
Each setting rebuilds sites, sightings, hops, training/calibration data and the group quartile edges from its own
events (trajectories are reused from the confirmation run, since they do not depend on these settings).
Primary predictor, reduced method set (posthoc.reduce_cfg; CityTrac-style dropped), evaluation seed 0.
"""
import argparse
import copy
import subprocess
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

from ccpilot import evaluate
from ccpilot.calibration import conformal_tau
from ccpilot.evaluate import _wilson_ub
from ccpilot.posthoc import load_work, reduce_cfg

BASE = "configs/porto_cctv_confirm.yaml"
PRED = "src_zone_hour_speed"
SETTINGS = {"r30": ("observation radius 30 m (merge radius 30 m)", {"cameras.merge_radius_m": 30, "events.camera_radius_m": 30}),
            "r75": ("observation radius 75 m (merge radius 75 m)", {"cameras.merge_radius_m": 75, "events.camera_radius_m": 75}),
            "tmax300": ("T_max 300 s", {"events.t_max_s": 300}),
            "tmax900": ("T_max 900 s", {"events.t_max_s": 900})}
METHODS = [("static", "static"), ("aci", "aci_g0005"), ("qr_ogd", "qr_ogd"), ("mvp_log", "mvp_log")]
ATTRS = ["hgroup", "hopkind", "speed_bin", "zone", "entropy_bin", "nn_bin"]
OUT = Path("results/porto_cctv_confirm_posthoc/geometry")


def cfg_path(name):
    return Path(f"configs/porto_cctv_confirm_geom_{name}.yaml")


def make_configs():
    base = yaml.safe_load(open(BASE, encoding="utf-8"))
    for name, (desc, ch) in SETTINGS.items():
        c = copy.deepcopy(base)
        for k, v in ch.items():
            a, b = k.split("."); c[a][b] = v
        c["work_dir"] = f"work/porto_cctv_confirm_geom_{name}"
        c["out_dir"] = str(OUT / name)
        c["porto"]["reuse_trajectories"] = "work/porto_cctv_confirm/trajectories.parquet"
        reduce_cfg(c, PRED)
        c["eval"].pop("citytrac", None)
        c["eval"]["save_hits"] = True
        c["eval"]["save_scores"] = {"tau_min_levels": [0.002]}
        head = (f"# POST-HOC (review M3, 2026-10-01): {desc}; otherwise the confirmation settings\n"
                f"# (configs/porto_cctv_confirm.yaml, not edited), held-out period only, primary predictor, reduced method set.\n"
                f"# Generated by posthoc_geometry.py; trajectories reused from the confirmation run.\n")
        cfg_path(name).write_text(head + yaml.safe_dump(c, sort_keys=False, allow_unicode=True))
        print("wrote", cfg_path(name))


def run():
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    for name in SETTINGS:
        t0 = time.time()
        r = subprocess.run([sys.executable, "run_pilot.py", "--config", str(cfg_path(name)), "--stage", "all"],
                           capture_output=True, text=True)
        (OUT / f"{name}.log").write_text(r.stdout + r.stderr)
        rows.append({"setting": name, "seconds": round(time.time() - t0, 1), "returncode": r.returncode})
        print(rows[-1], flush=True)
        if r.returncode != 0:
            break
    pd.DataFrame(rows).to_csv(OUT / "run_times.csv", index=False)


def summarize_run(out_dir, work_dir, label, hits_path=None):
    """25-group statistics per segment from a run's hits.parquet (oracle hits rebuilt from stored scores)."""
    H = pd.read_parquet(hits_path or Path(out_dir) / "hits.parquet")
    S = pd.read_csv(Path(out_dir) / "summary.csv"); S = S[S.predictor == PRED]
    n_sites = sum(1 for _ in open(Path(work_dir) / "cameras.csv")) - 1
    H["seg"] = H["segment"].replace({"B_early": "test_jun_b", "B_late": "test_jun_b"})
    rows = []
    for seg in ["test_jun_a", "test_jun_b"]:
        m = (H.seg == seg).to_numpy(); B = H[m]
        s = B[f"score|{PRED}"].to_numpy()
        orc = S[(S.method == "oracle(post-hoc)") & (S.segment == seg)].iloc[0]
        hits = {k: B[f"hit|{PRED}|{c}"].to_numpy().astype(bool) for k, c in METHODS}
        hits["oracle"] = s >= conformal_tau(s, 0.05)
        assert abs(hits["oracle"].mean() - orc["coverage"]) < 1e-12
        costs = {k: S[(S.method == c) & (S.segment == seg)].cost_mean_cam_s.iloc[0] for k, c in METHODS}
        costs["oracle"] = orc["cost_mean_cam_s"]
        for k, h in hits.items():
            G = [("grp_all=0", np.ones(len(B), bool))] + [(f"{d}={int(v)}", (B[d] == v).to_numpy()) for d in ATTRS for v in sorted(B[d].unique())]
            st = []
            for key, gm in G:
                n = int(gm.sum()); kk = int(h[gm].sum())
                st.append((key, n, kk / n, _wilson_ub(kk, n)))
            D = pd.DataFrame(st, columns=["key", "n", "recall", "ub95"]); J = D[D.n >= 200]
            rows.append({"setting": label, "segment": seg, "method": k, "n_sites": n_sites, "n_hops_segment": int(m.sum()),
                         "recall": h.mean(), "worst": J.recall.min(), "worst_key": J.loc[J.recall.idxmin(), "key"],
                         "below94": int((J.ub95 < 0.94).sum()), "below95": int((J.ub95 < 0.95).sum()),
                         "cost_cam_s": costs[k], "cost_ratio": costs[k] / costs["oracle"],
                         "structural_miss": orc["structural_miss"]})
    return pd.DataFrame(rows)


def summarize():
    base = yaml.safe_load(open(BASE, encoding="utf-8"))
    parts = [summarize_run("results/porto_cctv_confirm", base["work_dir"], "base",
                           hits_path="results/porto_cctv_confirm_posthoc/outage_suite/none_s7/hits.parquet")]
    meta = []
    for name in ["base"] + list(SETTINGS):
        c = base if name == "base" else yaml.safe_load(open(cfg_path(name), encoding="utf-8"))
        tr = pd.read_parquet(Path(c["work_dir"]) / "transitions.parquet", columns=["is_exit", "t_exit"])
        t0 = pd.Timestamp(c["eval"]["splits"]["test"][0]["range"][0], tz=c["timezone"]).timestamp()
        t1 = pd.Timestamp(c["eval"]["splits"]["test"][-1]["range"][1], tz=c["timezone"]).timestamp()
        held = tr[(tr.t_exit >= t0) & (tr.t_exit < t1)]
        meta.append({"setting": name, "exit_share_heldout": held.is_exit.mean(), "n_transitions_heldout": len(held),
                     "camera_radius_m": c["events"]["camera_radius_m"], "merge_radius_m": c["cameras"]["merge_radius_m"],
                     "t_max_s": c["events"]["t_max_s"]})
        if name != "base":
            parts.append(summarize_run(c["out_dir"], c["work_dir"], name))
    R = pd.concat(parts, ignore_index=True).merge(pd.DataFrame(meta), on="setting")
    OUT.mkdir(parents=True, exist_ok=True)
    R.to_csv(OUT / "geometry_summary.csv", index=False)
    pd.set_option("display.width", 250)
    print(R.round(4).to_string(index=False))


# ---------------------------------------------------------------- seed repetition (2026-10-01, M3 follow-up)
SEED_METHODS = [("static", "static"), ("aci", "aci_g0005"), ("qr_ogd", "qr_ogd"), ("mvp_log", "mvp_log"),
                ("oracle", "oracle(post-hoc)")]
SEED_DEP = {"aci", "qr_ogd", "mvp_log"}           # depend on the evaluation seed (feedback sample, MVP randomisation)


def seed_dir(name, sd):
    """hits/summary of setting `name`, evaluation seed sd (seed 0 = the run of --run; base = seeds_prereg25)."""
    if name == "base":
        return Path("results/porto_cctv_confirm_posthoc/seeds_prereg25") / f"seed_{sd}"
    return OUT / name if sd == 0 else OUT / name / "seeds" / f"seed_{sd}"


def run_seeds(seeds, names):
    for name in names:
        c0 = yaml.safe_load(open(cfg_path(name), encoding="utf-8"))
        work = load_work(c0)
        for sd in seeds:
            assert sd != 0, "seed 0 is the run of --run"
            c = copy.deepcopy(c0); c["eval"]["seed"] = sd
            t0 = time.time()
            evaluate.run(c, *work, seed_dir(name, sd))
            print({"setting": name, "seed": sd, "seconds": round(time.time() - t0, 1)}, flush=True)


def seed_stats(name, sd):
    """25-group statistics of one setting and seed; seed-invariant methods (static, oracle) are taken from seed 0."""
    d = seed_dir(name, sd)
    # seed-0 hops with scores (base: none_s7, whose hits equal the confirmation run) for static and the oracle
    p0 = Path("results/porto_cctv_confirm_posthoc/outage_suite/none_s7/hits.parquet") if name == "base" else seed_dir(name, 0) / "hits.parquet"
    H0 = pd.read_parquet(p0)
    H = pd.read_parquet(d / "hits.parquet")
    assert (H0["tr_id"].to_numpy() == H["tr_id"].to_numpy()).all()
    S = pd.read_csv(d / "summary.csv"); S = S[S.predictor == PRED]
    H["seg"] = H["segment"].replace({"B_early": "test_jun_b", "B_late": "test_jun_b"})
    rows = []
    for seg in ["test_jun_a", "test_jun_b"]:
        m = (H.seg == seg).to_numpy()
        B = H[m]; B0 = H0[m]
        s = B0[f"score|{PRED}"].to_numpy()
        orc = S[(S.method == "oracle(post-hoc)") & (S.segment == seg)].iloc[0]
        for k, c in SEED_METHODS:
            if k == "oracle":
                h = s >= conformal_tau(s, 0.05)
                assert abs(h.mean() - orc["coverage"]) < 1e-12
            else:
                h = (B0 if k not in SEED_DEP else B)[f"hit|{PRED}|{c}"].to_numpy().astype(bool)
            st = []
            for d_ in ["grp_all"] + ATTRS:
                v = np.zeros(len(B), int) if d_ == "grp_all" else B[d_].to_numpy()
                for g in sorted(np.unique(v)):
                    gm = v == g; n = int(gm.sum()); kk = int(h[gm].sum())
                    st.append((f"{d_}={int(g)}", n, kk / n, _wilson_ub(kk, n)))
            D = pd.DataFrame(st, columns=["key", "n", "recall", "ub95"]); J = D[D.n >= 200]
            bad = J[J.ub95 < 0.94]
            cost = S[(S.method == c) & (S.segment == seg)].cost_mean_cam_s.iloc[0]
            rows.append({"setting": name, "seed": sd, "segment": seg, "method": k, "recall": h.mean(),
                         "worst": J.recall.min(), "worst_key": J.loc[J.recall.idxmin(), "key"],
                         "below94": len(bad), "below94_keys": ";".join(bad.key),
                         "below94_recalls": ";".join(f"{x:.4f}" for x in bad.recall),
                         "below94_n": ";".join(str(int(x)) for x in bad.n),
                         "cost_cam_s": cost, "cost_ratio": cost / orc["cost_mean_cam_s"]})
    return rows


def summarize_seeds(seeds=(0, 1, 2, 3, 4)):
    rows = []
    for name in ["base"] + list(SETTINGS):
        for sd in seeds:
            rows += seed_stats(name, sd)
    R = pd.DataFrame(rows)
    # seed-invariant methods: identical across seeds (checked), so the pass count is 0 or 5
    for k in ["static", "oracle"]:
        chk = R[R.method == k].groupby(["setting", "segment"])[["recall", "below94", "cost_cam_s"]].nunique()
        assert (chk == 1).all().all(), k
    R.to_csv(OUT / "geometry_seeds.csv", index=False)
    P = []
    for (name, k), g in R.groupby(["setting", "method"], sort=False):
        per = g.groupby("seed").below94.sum()
        fails = g[g.below94 > 0]
        P.append({"setting": name, "method": k, "n_seeds": len(per), "n_pass": int((per == 0).sum()),
                  "failed_seeds": ";".join(str(x) for x in per[per > 0].index),
                  "failures": "; ".join(f"seed {r.seed} {r.segment[-1].upper()} {r.below94_keys} {r.below94_recalls} (n {r.below94_n})"
                                        for r in fails.itertuples()),
                  "cost_ratio_min": g.cost_ratio.min(), "cost_ratio_max": g.cost_ratio.max(),
                  "cost_ratio_mean_min": g.groupby("seed").cost_ratio.mean().min(),
                  "cost_ratio_mean_max": g.groupby("seed").cost_ratio.mean().max()})
    P = pd.DataFrame(P)
    P.to_csv(OUT / "geometry_seed_pass.csv", index=False)
    pd.set_option("display.width", 250); pd.set_option("display.max_colwidth", 200)
    print(P.round(4).to_string(index=False))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--make-configs", action="store_true"); ap.add_argument("--run", action="store_true")
    ap.add_argument("--summarize", action="store_true")
    ap.add_argument("--seeds", nargs="*", type=int)
    ap.add_argument("--settings", nargs="*", default=list(SETTINGS))
    ap.add_argument("--summarize-seeds", action="store_true")
    a = ap.parse_args()
    if a.make_configs:
        make_configs()
    if a.run:
        run()
    if a.summarize:
        summarize()
    if a.seeds:
        run_seeds(a.seeds, a.settings)
    if a.summarize_seeds:
        summarize_seeds()
